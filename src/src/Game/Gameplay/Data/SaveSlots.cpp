namespace {
	namespace fs = std::filesystem;
	struct SaveSlotsLog {};

	std::string Trainer(const std::string& name) {
		return SaveDirectory() + name + "/trainer.ini";
	}
}

std::vector<SaveSlots::Slot> SaveSlots::List() {
	auto out = std::vector<Slot>{};
	const auto directory = fs::path{ SaveDirectory() };
	auto error = std::error_code{};
	for (const auto& entry : fs::directory_iterator{ directory, error }) {
		const auto name = entry.path().filename().string();
		const auto trainer = entry.path() / "trainer.ini";
		if (!entry.is_directory() || name == "new_game" || !fs::exists(trainer)) {
			continue;
		}
		auto reader = ska::IniReader{ trainer.string() };
		const auto toGenerate = reader.exists("World generate") && reader.get<bool>("World generate");
		const auto map = !toGenerate && reader.exists("Trainer start_map_name") ? reader.get<std::string>("Trainer start_map_name") : std::string{};
		const auto played = fs::last_write_time(trainer, error).time_since_epoch().count();
		out.push_back(Slot{ name, map, static_cast<long long>(played) });
	}
	std::sort(out.begin(), out.end(), [](const Slot& a, const Slot& b) {
		return a.played != b.played ? a.played > b.played : a.name < b.name;
	});
	return out;
}

bool SaveSlots::Exists(const std::string& name) {
	return fs::exists(Trainer(name));
}

std::string SaveSlots::NewName() {
	for (auto i = 1;; i++) {
		const auto name = "partie" + std::to_string(i);
		if (!fs::exists(SaveDirectory() + name)) {
			return name;
		}
	}
}

std::int64_t SaveSlots::NewSeed() {
	const auto* seed = std::getenv("SAD_WORLD_SEED");
	if (seed != nullptr && *seed != '\0') {
		return std::atoll(seed);
	}
	auto device = std::random_device{};
	return std::uniform_int_distribution<std::int64_t>{ 1, 999999 }(device);
}

void SaveSlots::Create(const std::string& name, std::int64_t seed) {
	const auto save = fs::path{ SaveDirectory() + name };
	fs::create_directories(save);
	fs::copy("./Data/Saves/new_game", save, fs::copy_options::recursive | fs::copy_options::overwrite_existing);
	auto reader = ska::IniReader{ Trainer(name) };
	reader.set("World generate", true);
	reader.set("World seed", static_cast<long long>(seed));
	reader.save(Trainer(name));
	SLOG_STATIC(ska::LogLevel::Info, SaveSlotsLog) << "Savegame : new game " << name << " (world of seed " << seed << ")";
}

std::optional<std::int64_t> SaveSlots::WorldToGenerate(const std::string& name) {
	if (!Exists(name)) {
		return std::nullopt;
	}
	auto reader = ska::IniReader{ Trainer(name) };
	const auto toGenerate = reader.exists("World generate") && reader.get<bool>("World generate");
	// A world that is not there anymore (ex : left out of the web package) : generated again
	const auto directory = reader.exists("World directory") ? reader.get<std::string>("World directory") : std::string{};
	const auto map = reader.exists("Trainer start_map_name") ? reader.get<std::string>("Trainer start_map_name") : std::string{};
	const auto lost = !toGenerate && !directory.empty() && !fs::exists(directory + map + "/" + map + ".ini");
	// A world generated by an older game (worldgen::WorldVersion) : generated again, from its seed
	const auto version = reader.exists("World version") ? reader.get<int>("World version") : 1;
	const auto outdated = !toGenerate && !lost && reader.exists("World seed") && version < worldgen::WorldVersion;
	if (!toGenerate && !lost && !outdated) {
		return std::nullopt;
	}
	if (outdated) {
		SLOG_STATIC(ska::LogLevel::Info, SaveSlotsLog) << "Savegame : the world of " << name << " is of the version " << version
			<< " (the game makes " << worldgen::WorldVersion << ") : generated again";
	}
	if (reader.exists("World seed")) {
		return std::atoll(reader.get<std::string>("World seed").c_str());
	}
	// The saves made before the worlds were generated by the game : their world was ./Data/Worlds/seed<N>/
	const auto at = directory.rfind("seed");
	if (lost && at != std::string::npos) {
		const auto seed = std::atoll(directory.c_str() + at + 4);
		if (seed > 0) {
			return seed;
		}
	}
	return std::nullopt;
}

std::string SaveSlots::WorldPath(const std::string& name) {
	return SaveDirectory() + name + "/World/";
}

void SaveSlots::WorldGenerated(const std::string& name, std::int64_t seed, const worldgen::Start& start) {
	auto reader = ska::IniReader{ Trainer(name) };
	reader.set("World seed", static_cast<long long>(seed));
	const auto fresh = reader.exists("World generate") && reader.get<bool>("World generate");
	reader.set("World directory", WorldPath(name));
	reader.set("World generate", false);
	reader.set("World version", worldgen::WorldVersion);
	// The village where the game starts (its block of the world) : the wild Pokemon are stronger far from it
	const auto chunk = start.map.size() > 2 ? start.map.substr(2) : std::string{};
	const auto separator = chunk.find('_');
	if (separator != std::string::npos) {
		reader.set("World town_x", std::atoi(chunk.substr(0, separator).c_str()) * worldgen::Chunk + start.x);
		reader.set("World town_y", std::atoi(chunk.substr(separator + 1).c_str()) * worldgen::Chunk + start.y - 1);
	}
	// The entities of the chunks were of the world before
	std::remove((SaveDirectory() + name + "/Chunks.txt").c_str());
	if (fresh) { // a world generated again (the same seed, the same world) : the trainer stays where it was
		reader.set("Trainer start_map_name", start.map);
		reader.set("Trainer start_posx", start.x);
		reader.set("Trainer start_posy", start.y);
	}
	reader.save(Trainer(name));
}
